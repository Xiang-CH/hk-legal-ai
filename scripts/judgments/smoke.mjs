#!/usr/bin/env node
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import pg from 'pg';
import { execFileSync } from 'node:child_process';
import { importCorpus } from './ingest.mjs';
import { generateChunks, searchChunks } from './chunks.mjs';
import { embedPending } from './embed.mjs';
import { resolveReferences, readReferences } from './references.mjs';

const databaseUrl = process.env.JUDGMENT_DATABASE_URL;
if (!databaseUrl) throw Error('Explicit JUDGMENT_DATABASE_URL required');
const url = new URL(databaseUrl);
if (!['127.0.0.1','localhost'].includes(url.hostname) || !/^\/clic_judgment_test_/.test(url.pathname)) throw Error('Local disposable test database required');
const client = new pg.Client({connectionString:databaseUrl});
const root = await mkdtemp(path.join(tmpdir(),'judgment-smoke-'));
await client.connect();
try {
  const existing = await client.query('SELECT count(*)::int AS count FROM "Judgment"');
  assert.equal(existing.rows[0].count,0,'Smoke requires an empty migrated test database');
  const html = '<html><head><script>excluded</script></head><body><table><tr><td><h2>Liability</h2><p><a class="para" id="p1">1.</a> A landlord owes a duty of care. [2020] HKCA 2</p><p>Continuation belongs to paragraph one.</p><p><a class="para" id="p2">2.</a> Damages are assessed. [2020] 1 HKLRD 42; [2020] 1 HKC 99; [2019] HKCA 999; [2020] HKCFI 1. HCA42/2020. [1932] AC 562. <a href="https://hklii.hk/en/cases/hkca/2020/2.html#p3">Authority</a></p><table><tr><td>Amount</td><td>100</td></tr></table></td></tr></table></body></html>';
  for (const [id,court,number,language] of [[1,'HKCFI',1,'en'],[2,'HKCA',2,'en'],[3,'HKCFI',1,'tc'],[4,'HKCA',2,'tc'],[5,'HKCA',3,'en'],[6,'HKCA',4,'en']]) {
    await client.query('INSERT INTO "Judgment"(id,"neutralCitation","courtName",year,number,date,"languageCode","isTranslation","legalrefUrl",url) VALUES($1,$2,$3,2020,$4,$5,$6,false,$7,$7)',[id,`[2020] ${court} ${number}`,court,number,'2020-01-01',language,`/${language}/cases/${court}/2020/${number}.html`]);
  }
  await client.query('INSERT INTO "ParallelCitations"(id,citation,"languageCode","judgmentId") VALUES(1,$1,$2,2),(2,$1,$3,4),(3,$4,$2,2),(4,$4,$2,5)',['[2020] 1 HKLRD 42','en','tc','[2020] 1 HKC 99']);
  await client.query('INSERT INTO "Case"(id,"caseAct","actType",year,number,title,"cjrId","cjrDis") VALUES(1,$1,$2,2020,42,$3,1,1)',['HCA42/2020','HCA','A v B']);
  await client.query('INSERT INTO "_CaseToJudgment"("A","B") VALUES(1,2),(1,5)');
  await client.query(`INSERT INTO judgment_chunks(judgment_id,chunk_no,language_code,neutral_citation,court_name,year,content,url,tsv,embedding) VALUES(1,0,'en','[2020] HKCFI 1','HKCFI',2020,'Legacy landlord summary remains available','/en/cases/HKCFI/2020/1.html',to_tsvector('english','Legacy landlord summary remains available'),$1::halfvec)`,[JSON.stringify([1,...Array(3071).fill(0)])]);
  await client.query('INSERT INTO "LegislationCap"(id,"capNumber","languageCode",url,"updatedAt") VALUES(1,$1,$2,$3,now())',['134','en','/en/legis/ord/134/']);
  await client.query('INSERT INTO "LegislationSection"(id,path,"capNumber","sectionNumber",content,"languageCode",url) VALUES(1,$1,$2,$3,$4,$5,$6)',['134/4','134','4','Prohibited conduct','en','/en/legis/ord/134/s4']);
  await client.query('INSERT INTO "LegislationCap"(id,"capNumber","languageCode",url,"updatedAt") VALUES(2,$1,$2,$3,now())',['336H','en','/en/legis/reg/336H/']);
  await client.query('INSERT INTO "LegislationSection"(id,path,"capNumber","sectionNumber",content,"languageCode",url) VALUES(2,$1,$2,$3,$4,$5,$6)',['336H/22','336H','22','Subsidiary legislation','en','/en/legis/reg/336H/s22']);
  await client.query('INSERT INTO "_JudgmentToLegislationCap"("A","B") VALUES(1,1)');
  const source = path.join(root,'HKCFI/2020/1');
  await mkdir(source,{recursive:true});
  await writeFile(path.join(source,'EN.json'),JSON.stringify({content:html,noteup_links:{judgment:{neutral:['[2020] HKCA 2','[2020] HKCA 4'],parallel:[]},legis:['/en/legis/ord/134/','/en/legis/ord/134/s4','/en/legis/reg/336H/s22','/en/legis/ord/999Z/s1']}}));
  await writeFile(path.join(source,'tc.json'),JSON.stringify({content:'<body><p><a id="p1">1.</a> 業主有責任支付損害賠償。[2020] HKCA 2</p></body>'}));
  await writeFile(path.join(source,'EN_cit.json'),JSON.stringify(['[2020] 1 HKLRD 100']));
  const auditOutput = execFileSync(process.execPath,['scripts/judgments/audit.mjs','--dir',root],{env:{...process.env,JUDGMENT_DATABASE_URL:databaseUrl},encoding:'utf8',stdio:['ignore','pipe','pipe']});
  const auditRows=auditOutput.trim().split('\n').map(line=>JSON.parse(line));
  assert.equal(auditRows.filter(row=>row.status==='matched').length,2);
  assert.equal(auditRows.filter(row=>row.kind==='sidecar').length,1);
  const config = {client,root,apply:true,databaseUrl,testDatabase:true};
  const first = await importCorpus(config);
  assert.equal(first.outcomes.filter(row=>row.status==='imported').length,2);
  const second = await importCorpus(config);
  assert.equal(second.outcomes.filter(row=>row.status==='unchanged').length,2);
  const paragraphs = await client.query('SELECT p.* FROM judgment_paragraphs p JOIN judgment_documents d ON p.document_id=d.id WHERE d.judgment_id=1 ORDER BY p.position');
  assert(paragraphs.rows.find(row=>row.anchor==='p1').content.includes('Continuation'));
  assert(paragraphs.rows.some(row=>row.block_type==='table'));
  assert(!paragraphs.rows.some(row=>row.content.includes('excluded')));
  await resolveReferences({client,root,apply:true});
  const refs = await readReferences(client,2,{direction:'incoming'});
  assert(refs.references.some(row=>row.source_id===1));
  const outgoing=(await readReferences(client,1,{limit:100})).references;
  assert(outgoing.some(row=>row.original==='[2020] 1 HKLRD 42'&&row.target_id===2));
  assert(outgoing.some(row=>row.original==='[2020] 1 HKC 99'&&row.status==='ambiguous'&&row.target_id===null));
  assert(outgoing.some(row=>row.kind==='url'&&row.target_id===2));
  assert(outgoing.some(row=>row.kind==='action-number'&&row.status==='pending'&&row.candidates.length===2));
  assert(outgoing.some(row=>row.original==='[2020] HKCA 4'&&row.status==='pending'));
  assert(outgoing.some(row=>row.original==='[2019] HKCA 999'&&row.status==='not-in-corpus'));
  assert(outgoing.some(row=>row.original==='[1932] AC 562'&&row.status==='not-in-corpus'));
  assert(!outgoing.some(row=>row.status==='self'));
  assert((await readReferences(client,4,{direction:'incoming'})).references.some(row=>row.source_id===3));
  const legislation=(await readReferences(client,1)).legislation;
  assert.equal(legislation.filter(row=>row.status==='resolved').length,3);
  assert.equal(legislation.filter(row=>row.status==='not-in-corpus').length,1);
  assert.equal((await client.query('SELECT count(*)::int AS count FROM judgment_managed_legislation_links WHERE source_id=1')).rows[0].count,2);
  assert.equal((await client.query('SELECT count(*)::int AS count FROM "_JudgmentToLegislationSection" WHERE "A"=1')).rows[0].count,2);
  await resolveReferences({client,root,apply:true});
  assert.equal((await readReferences(client,2,{direction:'incoming'})).references.length,refs.references.length);
  const generated = await generateChunks({client,apply:true});
  assert(generated.chunks>=2);
  assert((await searchChunks({client,query:'landlord'})).some(row=>row.judgment_id===1));
  assert((await searchChunks({client,query:'損害賠償'})).some(row=>row.judgment_id===3));
  const allChunks = (await client.query('SELECT * FROM judgment_fulltext_chunks')).rows;
  for (const chunk of allChunks) {
    assert(chunk.embedding_input.includes('[2020]'));
    const blocks = (await client.query('SELECT * FROM judgment_paragraphs WHERE document_id=$1',[chunk.document_id])).rows;
    for (const span of chunk.spans) assert(blocks.find(block=>block.position===span.position).content.slice(span.start,span.end).length>0);
  }
  let calls=0;
  const embed=async inputs=>{calls++;return inputs.map(()=>[1,...Array(3071).fill(0)]);};
  const embedded=await embedPending({client,embed,apply:true,approveCost:true,maxTokens:10000,testProvider:true});
  assert(embedded.ready>0);
  const before=calls;
  await embedPending({client,embed,apply:true,approveCost:true,maxTokens:10000,testProvider:true});
  assert.equal(calls,before);
  assert((await searchChunks({client,query:'landlord',embedding:[1,...Array(3071).fill(0)]})).length>0);
  execFileSync('npx',['-y','tsx','scripts/judgments/verify-compatibility.ts'],{env:{...process.env,DATABASE_URL:databaseUrl},stdio:'inherit'});
  const currentSource=JSON.parse(await readFile(path.join(source,'EN.json'),'utf8'));
  await writeFile(path.join(source,'EN.json'),JSON.stringify({...currentSource,sourceRevision:2}));
  await importCorpus(config);
  await generateChunks({client,apply:true});
  const cached=await embedPending({client,embed:async()=>{throw Error('Unchanged embedding input must reuse cache');},apply:true,approveCost:true,maxTokens:10000,testProvider:true,retries:0});
  assert.equal(cached.requests,0);
  assert(cached.ready>0);
  await generateChunks({client,apply:true,modelVersion:'test-next'});
  const activeBefore=(await client.query('SELECT * FROM judgment_fulltext_active ORDER BY document_id')).rows;
  const denied=await embedPending({client,embed,apply:true,approveCost:true,maxTokens:1,testProvider:true});
  assert(denied.budgetExhausted);
  assert.equal(denied.requests,0);
  assert.deepEqual((await client.query('SELECT * FROM judgment_fulltext_active ORDER BY document_id')).rows,activeBefore,'Embedding must not reactivate a previous model generation');
  let firstAttempt=true;
  const retried=await embedPending({client,embed:async inputs=>{if(firstAttempt){firstAttempt=false;throw Error('Injected provider failure');}return embed(inputs);},apply:true,approveCost:true,maxTokens:10000,testProvider:true,retries:1});
  assert.equal(retried.requests,2);
  assert.equal(retried.failed,0);
  assert.deepEqual((await client.query('SELECT * FROM judgment_fulltext_active ORDER BY document_id')).rows,activeBefore);
  const beforeFailure=(await client.query('SELECT generation FROM judgment_documents WHERE judgment_id=1')).rows[0].generation;
  await client.query(`CREATE FUNCTION judgment_smoke_fail() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.content LIKE '%FAIL_IMPORT%' THEN RAISE EXCEPTION 'Injected storage failure'; END IF; RETURN NEW; END $$`);
  await client.query('CREATE TRIGGER judgment_smoke_fail BEFORE INSERT ON judgment_paragraphs FOR EACH ROW EXECUTE FUNCTION judgment_smoke_fail()');
  await writeFile(path.join(source,'EN.json'),JSON.stringify({content:'<p><a id="p1">1.</a> FAIL_IMPORT</p>'}));
  const failed=await importCorpus(config);
  assert.equal(failed.outcomes.filter(row=>row.status==='quarantined').length,1);
  assert.equal((await client.query('SELECT generation FROM judgment_documents WHERE judgment_id=1')).rows[0].generation,beforeFailure,'Failed replacement must roll back generation and paragraph deletion');
  assert((await searchChunks({client,query:'landlord'})).length>0);
  await client.query('DROP TRIGGER judgment_smoke_fail ON judgment_paragraphs');
  await client.query('DROP FUNCTION judgment_smoke_fail()');
  await writeFile(path.join(source,'EN.json'),JSON.stringify({content:'<p><a id="p1">1.</a> Replacement text only.</p>'}));
  await importCorpus(config);
  assert.equal((await searchChunks({client,query:'landlord'})).length,0,'Stale generation must not be searched');
  assert.equal((await readReferences(client,2,{direction:'incoming'})).references.length,0,'References from an old source generation must not appear current');
  assert.equal((await client.query('SELECT count(*)::int AS count FROM "_JudgmentToLegislationCap" WHERE "A"=1 AND "B"=1')).rows[0].count,1,'Pre-existing legislation links must survive source replacement');
  assert.equal((await client.query('SELECT count(*)::int AS count FROM judgment_managed_legislation_links WHERE source_id=1')).rows[0].count,0,'Owned outdated links must be removed');
  const chineseSource=JSON.parse(await readFile(path.join(source,'tc.json'),'utf8'));
  await writeFile(path.join(source,'tc.json'),JSON.stringify({...chineseSource,noteup_links:{legis:['/en/legis/reg/336H/s22']}}));
  await importCorpus(config);
  await resolveReferences({client,root,apply:true});
  assert.equal((await client.query('SELECT count(*)::int AS count FROM judgment_managed_legislation_links WHERE source_id=3 AND section_id=2')).rows[0].count,1);
  console.log(JSON.stringify({passed:true,documents:2,chunks:generated.chunks,providerCalls:calls,checks:['idempotent import','layout table paragraphs','continuations','tables','citation direction','reference reruns','bilingual lexical retrieval','source spans','embedding persistence','no-op embedding rerun','stale generation exclusion']}));
} finally {
  await client.end();
  await rm(root,{recursive:true,force:true});
}
